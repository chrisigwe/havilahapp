import { useEffect, useMemo, useState } from 'react'
import { useToast } from '../components/Toast'
import { loadReviewFlags, loadLateRepaymentFlags, setReviewHandled } from '../lib/data'
import { naira, lagosTime } from '../lib/format'

// "Needs a look" — the things worth asking about, in one place.
//
// This page does NOT decide that anyone has done anything wrong, and it
// is written so nobody reads it that way. A deleted sale is nearly
// always a typo being fixed; a big write-off is nearly always a real
// breakage. What was missing was any way to SEE those things: they sat
// in an audit table nobody opens, which is how a bottle came back onto
// a shelf after a count with no trace, and how ₦48,500 of folio charges
// disappeared without anyone noticing until it was looked for.
//
// So: every row is a question with a name and a figure attached. The
// wording stays neutral on purpose — "worth asking about", never
// "suspicious" — because the page will be read by the same people it
// names, and an accusation generated by a rule is worse than no page.

const KIND = {
  backdated_change: {
    title: 'Changed after the day',
    why: 'An entry for an earlier day was edited or deleted. Normal when a mistake is being corrected — worth seeing when that day has already been counted and closed.',
  },
  money_change: {
    title: 'A payment was changed',
    why: 'Payments and repayments are money. Any edit or deletion deserves a second pair of eyes, whatever the reason.',
  },
  many_deletions: {
    title: 'Several deletions by one person',
    why: 'Any single deletion is fine. A run of them is worth a conversation — usually it means someone is struggling with the entry screen.',
  },
  blank_count: {
    title: 'Counted blank',
    why: 'A count line was submitted with nothing in it. Not counted is not the same as zero, and the balance keeps whatever it had.',
  },
  self_verified: {
    title: 'Counted and verified alone',
    why: 'The point of verifying is that a second person looks. Same name on both ends means nobody did.',
  },
  heavy_writeoff: {
    title: 'A lot of PR and damage',
    why: 'Free drinks and breakages are part of the business. A large total against one name is worth understanding, not assuming.',
  },
  stale_reopen: {
    title: 'Reopened and never re-dated',
    why: 'A stay was reopened to fix something and checked out again on the wrong day, so it is charging nights the guest did not stay.',
  },
  overpaid: {
    title: 'Paid more than the bill',
    why: 'Either money is owed back to the guest, or a payment was recorded twice.',
  },
  left_owing: {
    title: 'Left still owing',
    why: 'The guest has gone and the bill was not settled.',
  },
  late_entry: {
    title: 'Entered days late',
    why: 'A sale recorded well after its day was missing when that day was counted, which shows up later as a stock variance nobody can explain.',
  },
  late_repayment: {
    title: 'Credit repaid late',
    why: 'Money recorded two days or more after the day it came in, when Match your Total Sales was already done for that day. The rule allows two days; one is the habit worth having. Named here so a pattern has somewhere to show itself.',
  },
}

const SEV = {
  high:  { label: 'Look at this', ring: 'border-clay',  text: 'text-clay' },
  watch: { label: 'Worth asking', ring: 'border-amber', text: 'text-amber' },
  note:  { label: 'For the record', ring: 'border-line', text: 'text-dim' },
}

const dt = v => {
  if (!v) return ''
  const d = new Date(v)
  return `${d.toLocaleDateString('en-NG', { day: 'numeric', month: 'short' })} ${lagosTime(v)}`
}

export default function Review({ boot }) {
  const [days, setDays] = useState(7)
  const [flags, setFlags] = useState(null)
  const [err, setErr] = useState(null)
  const [showHandled, setShowHandled] = useState(false)
  const [saving, setSaving] = useState(null)
  const toast = useToast()

  // Marking something handled stops it being counted tomorrow. It hides
  // no record: the entry it points at is untouched, and Put back undoes
  // it. Updated in place rather than reloading, so working down a list
  // does not reshuffle it under the reader's hands.
  async function mark(f, handled) {
    setSaving(f.key)
    try {
      await setReviewHandled(boot.staff.branch_id, f.key, handled)
      setFlags(list => list.map(x => x.key === f.key
        ? { ...x, handled, handled_by: handled ? boot.staff.full_name : null,
            handled_at: handled ? new Date().toISOString() : null,
            kind_open: (x.kind_open ?? 0) + (handled ? -1 : 1) }
        : x.kind === f.kind
          ? { ...x, kind_open: (x.kind_open ?? 0) + (handled ? -1 : 1) }
          : x))
    } catch (e) { toast(e.message || 'Could not save', 'error') }
    setSaving(null)
  }

  useEffect(() => {
    setFlags(null); setErr(null)
    Promise.all([
      loadReviewFlags(boot.staff.branch_id, days),
      loadLateRepaymentFlags(boot.staff.branch_id, days),
    ])
      .then(([a, b]) => setFlags([...(a || []), ...(b || [])]))
      .catch(e => { setErr(e.message || 'could not load'); setFlags([]) })
  }, [boot.staff.branch_id, days])

  // What is new since the last visit. Kept per device in localStorage:
  // it is a convenience, not a record, and a page that cannot open
  // because storage is blocked would be worse than one that forgets.
  const seenKey = `havilah.review.seen.${boot.staff.branch_id}`
  const [lastSeen] = useState(() => {
    try { return localStorage.getItem(seenKey) || null } catch { return null }
  })
  useEffect(() => {
    if (flags === null) return
    try { localStorage.setItem(seenKey, new Date().toISOString()) } catch { /* fine */ }
  }, [flags, seenKey])

  // One list, newest first (Chris, 13 November 2026 — "I would like to
  // see what's new, and I wouldn't want to waste much time there").
  //
  // The page used to group by kind behind ten collapsed headings, which
  // is the right shape for going through one kind of thing and the wrong
  // one for finding out what happened since yesterday. What each kind
  // MEANS is still worth saying, so it moved to the bottom, out of the
  // way of someone who only wants to look and leave.
  const shown = useMemo(() => {
    const list = (flags || []).filter(f => showHandled || !f.handled)
    return [...list].sort((a, b) =>
      String(b.happened || '').localeCompare(String(a.happened || '')))
  }, [flags, showHandled])

  const live = useMemo(() => (flags || []).filter(f => !f.handled), [flags])
  const isNew = f => !!lastSeen && !!f.happened && String(f.happened) > lastSeen
  const newCount = useMemo(() => live.filter(isNew).length, [live, lastSeen])
  const kindsHere = useMemo(
    () => [...new Set((flags || []).map(f => f.kind))], [flags])

  return (
    <div className="px-5 pb-10">
      <div className="py-3 border-b border-line mb-3">
        <h1 className="text-2xl font-bold">Needs a look</h1>
        <p className="text-dim text-sm mt-1">
          {live.length === 0
            ? `Nothing waiting at ${boot.branchName}.`
            : lastSeen
              ? `${newCount} new since you last looked · ${live.length} waiting in all.`
              : `${live.length} waiting at ${boot.branchName}.`}
        </p>
        <div className="flex flex-wrap items-center gap-2 mt-3">
          <button onClick={() => setShowHandled(v => !v)}
            className={`h-10 px-4 rounded-xl border font-semibold shrink-0 ${showHandled
              ? 'border-leaf text-leaf' : 'border-line text-dim'}`}>
            {showHandled ? 'Hiding nothing' : 'Show handled'}
          </button>
          <div className="flex gap-2 shrink-0">
            {[7, 14, 30].map(d => (
              <button key={d} onClick={() => setDays(d)}
                className={`h-10 px-3 rounded-xl border font-semibold text-sm shrink-0 ${days === d
                  ? 'bg-amber text-bg border-amber' : 'border-line text-dim'}`}>
                {d} days
              </button>
            ))}
          </div>
        </div>
      </div>

      {flags === null && <p className="text-dim py-8 text-center">Loading…</p>}
      {err && <p className="text-clay py-4">{err}</p>}

      {flags !== null && !shown.length && !err && (
        <p className="text-leaf py-8 text-center">
          {showHandled ? `Nothing in the last ${days} days.` : 'Nothing waiting. All clear.'}
        </p>
      )}

      <ul className="divide-y divide-line/60">
        {shown.map((f, i) => {
          const meta = KIND[f.kind] || { title: f.kind }
          const sev = SEV[f.severity] || SEV.note
          return (
            <li key={`${f.key}-${i}`} className={`py-3 ${f.handled ? 'opacity-45' : ''}`}>
              <div className="flex items-baseline gap-2">
                <span className={`text-xs font-bold ${sev.text} shrink-0`}>
                  {meta.title}
                </span>
                {isNew(f) && !f.handled && (
                  <span className="text-[10px] font-bold text-bg bg-amber rounded px-1.5 py-0.5 shrink-0">
                    NEW
                  </span>
                )}
                <span className="flex-1" />
                {f.amount != null && (
                  <span className={`tnum font-bold shrink-0 ${f.handled ? 'text-dim' : sev.text}`}>
                    {naira(Number(f.amount))}
                  </span>
                )}
              </div>
              <div className="mt-0.5">
                <span className="font-semibold">{f.who}</span>
                {f.where && <span className="text-dim"> · {f.where}</span>}
              </div>
              <p className="text-dim text-sm">{f.summary}</p>
              <div className="flex items-baseline gap-3 mt-1">
                <span className="flex-1 min-w-0 text-dim text-xs tnum truncate">
                  {f.happened ? dt(f.happened) : ''}
                  {f.handled && f.handled_by ? ` · handled by ${f.handled_by}` : ''}
                </span>
                <button onClick={() => mark(f, !f.handled)} disabled={saving === f.key}
                  className={`shrink-0 h-8 px-3 rounded-lg border text-xs font-semibold
                    disabled:opacity-40 ${f.handled
                      ? 'border-line text-dim' : 'border-leaf text-leaf'}`}>
                  {saving === f.key ? '…' : f.handled ? 'Put back' : 'Done'}
                </button>
              </div>
            </li>
          )
        })}
      </ul>

      {/* What the questions mean, parked at the bottom. Worth reading
          once, never worth scrolling past every day. */}
      {!!kindsHere.length && (
        <details className="mt-6">
          <summary className="text-dim text-sm cursor-pointer">What these mean</summary>
          <dl className="mt-3">
            {kindsHere.map(k => (
              <div key={k} className="mb-3">
                <dt className="font-semibold text-sm">{(KIND[k] || { title: k }).title}</dt>
                <dd className="text-dim text-sm">{(KIND[k] || {}).why || ''}</dd>
              </div>
            ))}
          </dl>
        </details>
      )}

      {!!live.length && (
        <p className="text-dim text-xs mt-6">
          Ask before concluding. Every one of these has an innocent explanation
          that is usually the right one.
        </p>
      )}
    </div>
  )
}
